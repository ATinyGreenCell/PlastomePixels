"""Pack the sample plastomes (GenBank) into src/samples.ts as 2-bit base64."""
import base64, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
CODE = {'A': 0, 'T': 1, 'C': 2, 'G': 3}

def read_gb(path):
    t = path.read_text()
    version = re.search(r'^VERSION\s+(\S+)', t, re.M).group(1)
    definition = ' '.join(re.search(r'^DEFINITION\s+(.*?)\n(?=\S)', t, re.M | re.S).group(1).split()).rstrip('.')
    seq = re.sub(r'[^A-Za-z]', '', t.split('\nORIGIN', 1)[1].split('\n//', 1)[0]).upper()
    assert set(seq) <= set('ATCG'), set(seq) - set('ATCG')
    return version, definition, seq

def pack(seq):
    out = bytearray((len(seq) + 3) // 4)
    for i, ch in enumerate(seq):
        out[i >> 2] |= CODE[ch] << (6 - 2 * (i & 3))
    return base64.b64encode(bytes(out)).decode()

entries = []
for key, fname in [('arabidopsis', 'NC_000932.gb'), ('amborella', 'Amborella_trichopoda.gb')]:
    v, d, s = read_gb(root / 'data' / fname)
    entries.append((key, v, d, s))
    print(key, v, len(s), d, file=sys.stderr)

lines = ['// Generated by scripts/make_samples.py — public NCBI/ENA plastome sequences, 2 bits per base.',
         'export interface Sample { key: string; id: string; title: string; length: number; data: string }',
         'export const SAMPLES: Sample[] = [']
for key, v, d, s in entries:
    lines.append(f'  {{ key: {key!r}, id: {v!r}, title: {d!r}, length: {len(s)}, data: {pack(s)!r} }},')
lines.append('];')
(root / 'src' / 'samples.ts').write_text('\n'.join(lines) + '\n')
