// Precomputes each sample's base composition and inverted repeats, so the page shows them at once.
import { writeFileSync } from 'node:fs';
import { SAMPLES } from '../src/samples';
import { unpack2bit, composition } from '../src/seq';
import { findQuadripartite } from '../src/analysis';

const meta: Record<string, unknown> = {};
for (const s of SAMPLES) {
  const codes = unpack2bit(s.data, s.length);
  meta[s.key] = { comp: composition(codes), quad: findQuadripartite(codes) };
}
writeFileSync(process.argv[2], `// Generated by scripts/sample-meta.ts from src/samples.ts. Do not edit.
import type { Quadripartite } from './analysis';
export const SAMPLE_META: Record<string, { comp: number[]; quad: Quadripartite | null }> = ${JSON.stringify(meta)};
`);
